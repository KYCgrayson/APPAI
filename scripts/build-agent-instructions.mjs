import { readFileSync, writeFileSync } from 'node:fs';

export const specTopics = ['pages', 'style', 'i18n', 'tools', 'apps', 'api'];
export function buildAgentInstructions() {
  return '<!-- Generated by npm run spec:build; edit docs/spec/ instead. -->\n' +
    ['overview', ...specTopics].map(name => readFileSync(new URL(`../docs/spec/${name}.md`, import.meta.url), 'utf8').trimEnd()).join('\n\n') + '\n';
}
if (process.argv[1] === new URL(import.meta.url).pathname) {
  writeFileSync(new URL('../AGENT_INSTRUCTIONS.md', import.meta.url), buildAgentInstructions());
}
