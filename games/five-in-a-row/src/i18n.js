function matchLocale(raw) {
  const tag = String(raw).replaceAll('_', '-').toLowerCase();
  const exact = LOCALES.find((locale) => locale.toLowerCase() === tag);
  if (exact) return exact;
  if (tag.split('-')[0] === 'zh') return /(?:^|-)(?:hant|tw|hk|mo)(?:-|$)/.test(tag) ? 'zh-TW' : 'zh-CN';
  return LOCALES.find((locale) => locale === tag.split('-')[0]) ?? null;
}
export function detectLanguage(query, languages = []) {
  if (query) {
    const match = matchLocale(query);
    if (match) return match;
  }
  // Exact and Chinese-script matches have priority across the preference list.
  for (const tag of languages) {
    const exact = LOCALES.find((locale) => locale.toLowerCase() === String(tag).toLowerCase());
    if (exact) return exact;
    if (/^zh(?:-|$)/i.test(tag)) return matchLocale(tag);
  }
  for (const tag of languages) {
    const match = matchLocale(tag);
    if (match) return match;
  }
  return 'en';
}
export function translate(lang, key, values = {}) {
  const message = STRINGS[lang][key];
  const template = typeof message === 'string' ? message : message[new Intl.PluralRules(lang).select(values.count)] ?? message.other;
  return template.replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? ''));
}
